-- Routes/Routes.lua: reads the compiled route data (Routes/Data_<Faction>.lua, generated by
-- tools/routekit) and puts the route of one race and class together. Pure Lua, no WoW API,
-- so the offline tests run the same code. Layout of the data: docs/ROUTE-FORMAT.md.
local _, ns = ...

local R = {}
ns.Routes = R

-- Element layout { verb, ...arguments, sources, status [, roots] }.
R.VERB = {
	ACCEPT = 1,
	COMPLETE = 2,
	TURNIN = 3,
	COLLECT = 4,
	GOTO = 5,
	TRAVEL = 6,
	HS = 7,
	SETHOME = 8,
	FP = 9,
	TRAIN = 10,
	XP = 11,
	NOTE = 12,
}
-- Bits of the sources field.
R.SOURCE = { polestar = 1, att = 2, eglink = 4, own = 8, plan = 16 }
R.STATUS = { UNCONFIRMED = 0, CONFIRMED = 1 }

local loaded = {}

-- Builds the data of one faction once; nil if the faction has no data.
function R.Load(faction)
	local data = loaded[faction]
	if data == nil then
		local build = ns.RouteData and ns.RouteData[faction]
		data = build and build() or false
		loaded[faction] = data
	end
	return data or nil
end

-- Drops the builder functions of every faction, so the bytecode of the faction that is not
-- played can be collected. Call after R.Load for the player's faction; a character of the
-- other faction comes with a new UI session.
function R.Release()
	if ns.RouteData then
		for faction in pairs(ns.RouteData) do
			ns.RouteData[faction] = nil
		end
	end
end

local function allows(list, value)
	if not list then
		return true
	end
	for i = 1, #list do
		if list[i] == value then
			return true
		end
	end
	return false
end

local function applies(t, raceID, classID)
	return allows(t.r, raceID) and allows(t.c, classID)
end
R.Applies = applies

-- Module keys in route order for one race and class, or nil. swap (optional, Welle 7 stage 2): the
-- player's choices at switch points, { [module key] = key of the alternative module that replaces it };
-- a replacement the data does not hold is ignored. Inserts after a replaced module stay after it (R24).
function R.ModuleKeys(data, mode, raceID, classID, swap)
	local c = data and data.compose[mode]
	if not c then
		return nil
	end
	local start
	for _, s in ipairs(c.starts) do
		if applies(s, raceID, classID) then
			start = s.key
			break
		end
	end
	if not start then
		return nil
	end
	local function pick(key)
		local alt = swap and swap[key]
		return alt and data.modules and data.modules[alt] and alt or key
	end
	local keys = { pick(start) }
	local function inserts(anchor)
		for _, ins in ipairs(c.inserts) do
			if ins.after == anchor and applies(ins, raceID, classID) then
				keys[#keys + 1] = ins.key
			end
		end
	end
	inserts("start")
	for _, key in ipairs(c.core) do
		keys[#keys + 1] = pick(key)
		inserts(key)
	end
	return keys
end

-- The steps of one race and class in order: { { module = key, step = stepTable }, ... }.
-- Step tables are the compiled data itself (read only). Elements with their own filter are
-- rare; a caller checks them with R.Applies(element, raceID, classID). swap: see R.ModuleKeys.
function R.Steps(faction, mode, raceID, classID, swap)
	local data = R.Load(faction)
	if not data then
		return nil
	end
	local keys = R.ModuleKeys(data, mode, raceID, classID, swap)
	if not keys then
		return nil
	end
	local out = {}
	for _, key in ipairs(keys) do
		local m = data.modules[key]
		if m and applies(m, raceID, classID) then
			for _, step in ipairs(m.steps) do
				if applies(step, raceID, classID) then
					out[#out + 1] = { module = key, step = step }
				end
			end
		end
	end
	return out
end
