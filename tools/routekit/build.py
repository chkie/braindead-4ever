"""Baukasten builder: data/plan/*.toml + data/facts -> data/routes/<faction>/*.route + COMPOSE.

A computed route ("Rechenroute"), not a played one: the start zones come from the plan, the zone
order, the choice and the order of the quests from the route optimizer (tools/routekit/optimize.py,
Welle 6b), which prices every choice in the simulator's time and XP model; quests, coordinates
and prerequisites come from data/facts. Every element carries its sources and the status
"unbestätigt"; every module carries the label "vorläufig".

After building, the linter checks all 56 combinations; quests that cause errors are left out
and the modules are built again, until the linter is clean.
"""

import collections
import os
import shutil
import tomllib

from . import game, lint, routefmt
from .io import read_json, repo_path

LEVEL_ABOVE = lint.LEVEL_ABOVE
SAME_SPOT = 15.0  # yards: actions this close share one step
EXCLUDED_TYPES = {1, 41, 62, 81, 82, 83, 84}
MAX_ROUNDS = 12


def _src(field):
    return ",".join(field.get("src") or field.get("seen") or [])


class Pool:
    """Quests of one module with what is needed to schedule them."""

    def __init__(self, facts, faction, races, mode, exclude):
        self.facts = facts
        self.faction = faction
        self.races = set(races)
        self.mode = mode
        self.exclude = exclude

    def usable(self, r, allow_class):
        if r["q"] in self.exclude:
            return False
        if r.get("type") in EXCLUDED_TYPES or r.get("repeatable") or r.get("startItem"):
            return False
        # Quests ATT lists under an instance belong to the dungeon hint, not to the route, unless
        # Polestar types them as an ordinary quest (type 0, e.g. Red Silk Bandanas in Westfall).
        if r.get("instance") is not None and r.get("type") != 0:
            return False
        if self.mode == "speed" and (r.get("breadcrumb") or r["pre"]["state"] != "secured"):
            return False
        side = r.get("side", {}).get("v")
        if side not in ("B", self.faction[0]):
            return False
        qr = r.get("races", {}).get("v")
        if qr is not None and not (set(qr) & self.races):
            return False
        qc = r.get("classes", {}).get("v")
        if qc is not None and not allow_class:
            return False
        if not r.get("startPos") or not r.get("endPos"):
            return False
        return True


def _goto_line(verb, q, pos, facts):
    r = facts.q[q]
    if verb == "accept":
        field = r["startPos"]
        psrc, roots = ",".join(field["src"]), field.get("roots", 1)
    elif verb == "turnin":
        field = r["endPos"]
        psrc, roots = ",".join(field["src"]), field.get("roots", 1)
    else:
        o = next(o for o in r["obj"] if o.get("pos"))
        psrc, roots = ",".join(o["src"]), 1
    return "  goto %d %.1f,%.1f r=10 | src=%s status=unbestätigt roots=%d" % (pos[0], pos[1], pos[2], psrc, roots)


def _el_line(verb, q, facts):
    r = facts.q[q]
    if verb == "accept":
        src = _src(r.get("start", {})) or _src(r.get("startPos", {}))
    elif verb == "turnin":
        src = _src(r.get("end", {})) or _src(r.get("endPos", {}))
    else:
        src = ",".join(sorted({x for o in r.get("obj", []) for x in o.get("src", [])}))
    return "  %s %d | src=%s status=unbestätigt" % (verb, q, src)


def _header(key, kind, faction, mode, levels, sources, for_filter=None, text=None):
    out = [
        "-- SPDX-License-Identifier: GPL-3.0-only",
        "-- Generated by tools/routekit (build) from data/plan and data/facts. Computed route, not played.",
        "-- Contains data from Polestar forever-db (GPL-3.0-only), EG Link (CC BY 4.0, Efficient Games)",
        "-- and All The Things (MIT); see NOTICE.",
        "#module %s" % key,
        "#kind %s" % kind,
        "#faction %s" % faction,
        "#mode %s" % mode,
        "#levels %d-%d" % tuple(levels),
    ]
    if for_filter:
        out.append("#for %s" % for_filter)
    if text:
        out.append("#text %s" % text)
    out += ["#label vorläufig", "#version 1", "#sources %s" % sources, ""]
    return out


def _sources_header():
    meta = read_json(repo_path("data", "facts", "FACTS.json"))
    parts = []
    for s in ("polestar", "att", "eglink"):
        m = meta["sources"].get(s)
        if m:
            v = m.get("version")
            parts.append("%s=%s%s" % (s, (v + "@") if v else "", m["commit"][:7]))
    return " ".join(parts)


def zone_budget(faction, mode):
    """Guard P9: the core may not change zones more often than the start route did for the
    combination with the fewest zone changes (data/plan/metrics-baseline.json)."""
    import json

    from . import metrics

    try:
        with open(metrics.BASELINE_PATH, encoding="utf-8") as fh:
            base = json.load(fh)
    except FileNotFoundError:
        return None
    races = {game.RACES[r][0] for r in game.races_of(faction)}
    vals = [c["p9_changes"] for k, c in base["combos"].items() if k.split("/")[0] == mode and k.split("/")[1] in races]
    return min(vals) if vals else None


def build_faction(plan, facts, params, mode, exclude, sources, report, speed=None):
    from . import optimize

    import json

    from . import metrics

    try:
        with open(metrics.BASELINE_PATH, encoding="utf-8") as fh:
            baseline = json.load(fh)
    except FileNotFoundError:
        baseline = None
    if mode == "explorer" and speed is not None:
        planner = optimize.derive_explorer(speed, facts, params, plan, exclude, sources)
    else:
        planner = optimize.plan_faction(facts, params, plan, mode, exclude, sources, zone_budget(plan["faction"], mode),
                                        baseline, log=print)
    files, compose = optimize.emit_all(planner, sources)
    report["%s %s" % (plan["faction"], mode)] = planner.report
    return files, compose, planner


def write_all(plans, facts, exclude, params=None, report=None):
    from . import sim

    params = params or sim.Params.load()
    report = {} if report is None else report
    sources = _sources_header()
    root = repo_path("data", "routes")
    counts = collections.Counter()
    for plan in plans:
        fdir = os.path.join(root, plan["faction"].lower())
        if os.path.isdir(fdir):
            shutil.rmtree(fdir)  # only the factions built now; another process may build the other one
        os.makedirs(fdir, exist_ok=True)
        comp_lines = [
            "-- SPDX-License-Identifier: GPL-3.0-only",
            "-- Generated by tools/routekit (build). Which modules make the route for a race and class.",
            "#faction %s" % plan["faction"],
        ]
        speed = None
        for mode in routefmt.MODES:
            files, compose, planner = build_faction(plan, facts, params, mode, exclude, sources, report, speed)
            if mode == "speed":
                speed = planner
            for key, lines in files.items():
                with open(os.path.join(fdir, key + ".route"), "w", encoding="utf-8", newline="\n") as fh:
                    fh.write("\n".join(lines) + "\n")
                counts["modules"] += 1
            comp_lines += compose
        with open(os.path.join(fdir, "COMPOSE"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(comp_lines) + "\n")
    return counts


def load_plans():
    plans = []
    for name in ("alliance", "horde"):
        with open(repo_path("data", "plan", name + ".toml"), "rb") as fh:
            plans.append(tomllib.load(fh))
    return plans


def run(faction=None):
    """Builds both factions, or one (`faction`; two processes can build the two factions at once,
    the optimizer is deterministic either way)."""
    facts = lint.Facts.load()
    plans = [p for p in load_plans() if faction is None or p["faction"] == faction]
    exclude = set()
    report = {}
    for rnd in range(1, MAX_ROUNDS + 1):
        counts = write_all(plans, facts, exclude, report=report)
        mods, comps = lint.load_routes()
        combos = None
        if faction is not None:
            mods = {k: m for k, m in mods.items() if m.faction == faction}
            comps = [c for c in comps if c.faction == faction]
            combos = [(r, c) for r in game.races_of(faction) for c in game.COMBOS[r]]
        errs = lint.lint_all(mods, comps, facts, combo_list=combos)
        bad = {e.quest for e in errs if e.quest is not None}
        if not errs:
            return {"rounds": rnd, "modules": counts["modules"], "excluded": len(exclude), "report": report}
        if not bad:
            for e in errs[:20]:
                print(e)
            raise SystemExit("build: %d linter errors without a quest to leave out" % len(errs))
        exclude |= bad
    for e in errs[:20]:
        print(e)
    raise SystemExit("build: linter still finds %d errors after %d rounds" % (len(errs), MAX_ROUNDS))
